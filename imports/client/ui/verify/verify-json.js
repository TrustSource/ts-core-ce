import {Meteor} from 'meteor/meteor';
import {Template} from 'meteor/templating';
import {Session} from 'meteor/session';
import {$} from 'meteor/jquery';
import Notify from '/imports/api/notify';
import {Config} from '/imports/config';


Template.verifyJson.onRendered(function () {
  Session.set('checkResults')
  $('#verifyForm').validate({
    rules: {
      inputBody: {
        required: true
      }
    },
    errorElement: 'span',
    errorPlacement: function (error, element) {
      $(element)
        .closest('form')
        .find('label[for="' + element.attr('id') + '"]')
        .append(error);
    },
    submitHandler: function (form) {
      Session.set('requestInProgress', true);
      const inputBody = $(form).find('[name=inputBody]').val();
      try {
        const data = JSON.parse(inputBody)
        Meteor.callAsync('Signature.Verify', data).then(function(data) {
          if (data) {
            Session.set('checkResults',data);
            if(data.status === 200){
              Notify.success(data.message);
            }else{
              Notify.warn(data.message);
            }
          } else {
            let textError = 'Error: could not verify signature';
            Session.set('checkResults',{error:textError});
            Notify.danger(textError);
          }
        }).finally(function() {
          Session.set('requestInProgress', false);
        });
      }catch (e) {
        let textError = e.toString();
        Notify.danger(textError);
        Session.set('checkResults',{error:textError});
        Session.set('requestInProgress', false);
      }
    }
  });
});

Template.verifyJson.helpers({
  pageDescription: function () {
    return 'Verify content of sBOM, CSAF, CBOM or Notice file generated by ' + Config.name;
  },
  checkResults: function () {
    return Session.get('checkResults')
  },
  requestInProgress: function () {
    return Session.get('requestInProgress')
  },
  isOK: function () {
    let result = Session.get('checkResults')
    return result && result.status && result.status === 200
  }
});
